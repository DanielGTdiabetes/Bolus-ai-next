"""Capture candidate vectors from Legacy `_calculate_core` (ADR 0024).

Read-only audit tool. It loads `backend/app/services/bolus_engine.py` from a local, detached checkout of
`DanielGTdiabetes/bolus_ai` pinned to an exact SHA, replaces only the two model imports that `_calculate_core`
does not use, and evaluates the pure function on synthetic inputs. It never imports Legacy settings, databases,
network clients or services and never writes to Legacy.

Usage (run with `python3 -I` from outside the checkout):
    python3 -I capture_candidate_vectors.py <legacy-checkout> <expected-sha> > CandidateLegacyVectors.kt
"""
