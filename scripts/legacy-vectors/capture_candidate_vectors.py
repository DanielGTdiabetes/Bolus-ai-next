def load_core(checkout):
    stub_v2 = types.ModuleType("app.models.bolus_v2")
    for name in ("BolusRequestV2", "BolusResponseV2", "BolusSuggestions", "GlucoseUsed", "UsedParams"):
        setattr(stub_v2, name, type(name, (), {}))
    stub_settings = types.ModuleType("app.models.settings")
    stub_settings.UserSettings = type("UserSettings", (), {})
    for name in ("app", "app.models", "app.services", "app.dtos"):
        sys.modules.setdefault(name, types.ModuleType(name))
    sys.modules["app.models.bolus_v2"] = stub_v2
    sys.modules["app.models.settings"] = stub_settings
    dtos = types.ModuleType("app.dtos.math_models")
    exec(compile(open(f"{checkout}/backend/app/dtos/math_models.py", encoding="utf-8").read(), "math_models.py", "exec"), dtos.__dict__)
    sys.modules["app.dtos.math_models"] = dtos
    engine = types.ModuleType("app.services.bolus_engine")
    exec(compile(open(f"{checkout}/backend/app/services/bolus_engine.py", encoding="utf-8").read(), "bolus_engine.py", "exec"),
         engine.__dict__)
    return engine._calculate_core, dtos.CalculationInput


def kotlin_double(value):
    bits = int.from_bytes(struct.pack(">d", value), "big")
    return f"Double.fromBits(0x{bits:016x}uL.toLong()) /* {value!r} */"


def main():
    # Legacy sources are UTF-8 and the generated file is UTF-8 with LF, whatever the platform locale (Windows CI).
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    checkout, expected_sha = sys.argv[1], sys.argv[2]
    sha = subprocess.check_output(["git", "-C", checkout, "rev-parse", "HEAD"], text=True).strip()
    if sha != expected_sha:
        raise SystemExit(f"Legacy checkout is at {sha}, expected {expected_sha}")
    core, calculation_input = load_core(checkout)
    print("package org.bolusai.engine.candidate")
    print()
    print("// GENERATED by scripts/legacy-vectors/capture_candidate_vectors.py. Do not edit by hand.")
    print(f"// Source: DanielGTdiabetes/bolus_ai@{sha} backend/app/services/bolus_engine.py::_calculate_core")
    print("// Synthetic inputs. Every other Legacy feature disabled explicitly. Observed behaviour, not clinical approval.")
    print()
    print("internal class LegacyVector(")
    print("    val name: String, val carbs: String, val carbRatio: String, val sensitivity: String, val target: String,")
    print("    val glucose: String, val iob: String, val maxCorrection: String, val roundStep: String, val maxBolus: String,")
    print("    val mealU: Double, val correctionU: Double, val iobAppliedU: Double, val totalU: Double,")
    print(")")
    print()
    print(f"internal const val LEGACY_VECTORS_SHA: String = \"{sha}\"")
    print()
    print("internal val LEGACY_VECTORS: List<LegacyVector> = listOf(")
    for name, carbs, cr, isf, target, bg, iob, max_corr, step, max_bolus in CASES:
        result = core(calculation_input(
            carbs_g=carbs, target_mgdl=target, cr=cr, isf=isf, fiber_g=0.0, fat_g=0.0, protein_g=0.0,
            bg_mgdl=bg, bg_trend=None, bg_is_stale=False, bg_age_minutes=0.0, iob_u=iob, autosens_ratio=1.0,
            alcohol_mode=False, exercise_minutes=0, use_fiber_deduction=False, max_bolus_u=max_bolus,
            max_correction_u=max_corr, round_step=step, warsaw_enabled=False, dual_bolus_enabled=False,
            techne_enabled=False, strategy="normal", max_iob_u=None, min_bolus_interval_min=0,
            last_bolus_minutes=None))
        assert result.later_u == 0.0, name
        text = lambda v: (repr(v)[:-2] if repr(v).endswith(".0") else repr(v))
        print(f"    LegacyVector(\"{name}\", \"{text(carbs)}\", \"{text(cr)}\", \"{text(isf)}\", \"{text(target)}\",")
        print(f"        \"{text(bg)}\", \"{text(iob)}\", \"{text(max_corr)}\", \"{text(step)}\", \"{text(max_bolus)}\",")
        print(f"        {kotlin_double(result.meal_u)},")
        print(f"        {kotlin_double(result.corr_u)},")
        print(f"        {kotlin_double(result.iob_devoured)},")
        print(f"        {kotlin_double(result.total_u)}),")
    print(")")


if __name__ == "__main__":
    main()
